    public static String[] getRandomMask() {
            if (RANDOM.nextDouble() < PREDEFINED_PROBABILITY) {
                    int index = RANDOM.nextInt(PREDEFINED_MASKS.length);
                    return PREDEFINED_MASKS[index];
            }
            else {
                    return generateRandomMask();
            }
    }

        public static String[] generateRandomMask() {
                // Определяем количество '+', '=' и '-'
                int totalNonDot = RANDOM.nextInt(10 + 1) + 27;

                // Выбираем количество '+' и '=' с учётом ограничений
                int plus, equal;
                do {
                        plus = RANDOM.nextInt(5 + 1) + 2;
                        equal = RANDOM.nextInt(7 + 1) + 5; // 5..12
                } while (plus + equal > totalNonDot); // Сумма не должна превышать общее число

                int minus = totalNonDot - plus - equal;

                // Создаём плоский список из 200 '.' (20x10)
                char[] flat = new char[200];
                for (int i = 0; i < 200; i++) {
                        flat[i] = '.';
                }

                // Список индексов для случайного размещения
                List<Integer> indices = new ArrayList<>(200);
                for (int i = 0; i < 200; i++) {
                        indices.add(i);
                }
                Collections.shuffle(indices, RANDOM);

                // Расставляем символы
                for (int i = 0; i < plus; i++) {
                        flat[indices.get(i)] = '+';
                }
                for (int i = plus; i < plus + equal; i++) {
                        flat[indices.get(i)] = '=';
                }
                for (int i = plus + equal; i < totalNonDot; i++) {
                        flat[indices.get(i)] = '-';
                }

                // Собираем строки
                String[] result = new String[10];
                for (int row = 0; row < 10; row++) {
                        StringBuilder sb = new StringBuilder(20);
                        for (int col = 0; col < 20; col++) {
                                sb.append(flat[row * 20 + col]);
                        }
                        result[row] = sb.toString();
                }
                return result;
        }

